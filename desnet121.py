import random, numpy as np, pandas as pd, torch, torch.nn as nn, torch.optim as optim
import torchvision.transforms as transforms, medmnist, matplotlib.pyplot as plt
from torch.utils.data import DataLoader
from torchvision.models import densenet121, DenseNet121_Weights
from sklearn.metrics import confusion_matrix, roc_auc_score, roc_curve

# %% Cell 2: settings
SEED, IMAGE_SIZE, BATCH_SIZE, EPOCHS, LR = 7, 64, 32, 10, 1e-4
device = torch.device("cuda" if torch.cuda.is_available() else "cpu")

# %% Cell 3: data, and CALCULATE the weights from the training counts
info = medmnist.INFO["pneumoniamnist"]
DataClass = getattr(medmnist, info["python_class"])
tf = transforms.Compose([transforms.ToTensor(),
                         transforms.Normalize([0.485, 0.456, 0.406], [0.229, 0.224, 0.225])])
train_ds = DataClass(split="train", transform=tf, download=True, size=IMAGE_SIZE, as_rgb=True)
val_ds   = DataClass(split="val",   transform=tf, download=True, size=IMAGE_SIZE, as_rgb=True)
val_loader = DataLoader(val_ds, BATCH_SIZE, shuffle=False, num_workers=2)

counts = np.bincount(train_ds.labels.flatten())          # [normal, pneumonia]
inv = counts.sum() / (2 * counts)                        # inverse-frequency formula
print("Counts [normal, pneumonia]:", counts)
print("Inverse-frequency weights:", inv.round(2))
print("Total influence per class (count x weight):", (counts * inv).round(0))

CONFIGS = {"No weights": [1.0, 1.0],
           "Inverse frequency": list(inv)}              # add more, e.g. "Sqrt": list(np.sqrt(inv))

# %% Cell 4: train one config, return validation probabilities from the best epoch (by AUC)
@torch.no_grad()
def predict(model):
    model.eval(); ys, ps = [], []
    for x, y in val_loader:
        ps.extend(torch.softmax(model(x.to(device)), 1)[:, 1].cpu().numpy())
        ys.extend(y.view(-1).numpy())
    return np.array(ys), np.array(ps)

def train(weights):
    random.seed(SEED); np.random.seed(SEED); torch.manual_seed(SEED); torch.cuda.manual_seed_all(SEED)
    torch.backends.cudnn.deterministic = True; torch.backends.cudnn.benchmark = False
    g = torch.Generator(); g.manual_seed(SEED)
    loader = DataLoader(train_ds, BATCH_SIZE, shuffle=True, generator=g, num_workers=2)
    model = densenet121(weights=DenseNet121_Weights.DEFAULT)
    model.classifier = nn.Linear(model.classifier.in_features, 2)
    model = model.to(device)
    crit = nn.CrossEntropyLoss(weight=torch.tensor(weights, dtype=torch.float32).to(device))
    opt = optim.Adam(model.parameters(), lr=LR)
    best_auc, best = -1, None
    for ep in range(1, EPOCHS + 1):
        model.train()
        for x, y in loader:
            opt.zero_grad(); crit(model(x.to(device)), y.view(-1).long().to(device)).backward(); opt.step()
        ys, ps = predict(model); auc = roc_auc_score(ys, ps)
        print(f"   epoch {ep:02d}  val AUC {auc:.4f}")
        if auc > best_auc: best_auc, best = auc, (ys, ps, ep)
    return best

# %% Cell 5: run every config
preds = {}
for name, w in CONFIGS.items():
    print(f"\n=== {name}: weights {np.round(w, 2)} ===")
    preds[name] = train(w)

# %% Cell 6: evaluation table (at 0.5 AND threshold-free)
def metrics(ys, ps, thr=0.5):
    tn, fp, fn, tp = confusion_matrix(ys, (ps >= thr).astype(int), labels=[0, 1]).ravel()
    fpr, tpr, _ = roc_curve(ys, ps); ok = tpr >= 0.95
    return dict(AUC=roc_auc_score(ys, ps),
                Spec_at_Recall95=(1 - fpr[ok].min()) if ok.any() else np.nan,
                Recall_at_0p5=tp / (tp + fn), Specificity_at_0p5=tn / (tn + fp),
                Accuracy=(tp + tn) / len(ys), TP=tp, TN=tn, FP=fp, FN=fn)

rows = []
for name, (ys, ps, ep) in preds.items():
    rows.append(dict(Config=name, BestEpoch=ep, **metrics(ys, ps)))
table = pd.DataFrame(rows)
display(table.round(4))
# Read: AUC first -> Spec_at_Recall95 -> recall/specificity at 0.5. Gaps under ~0.01 AUC = noise.

# %% Cell 7: ROC curves + confusion matrices
fig, ax = plt.subplots(1, 1 + len(preds), figsize=(5 * (1 + len(preds)), 4))
for name, (ys, ps, ep) in preds.items():
    fpr, tpr, _ = roc_curve(ys, ps)
    ax[0].plot(fpr, tpr, label=f"{name} (AUC {roc_auc_score(ys, ps):.3f})")
ax[0].plot([0, 1], [0, 1], "k--", lw=0.8); ax[0].axhline(0.95, color="gray", ls=":", lw=0.8)
ax[0].set_xlabel("False positive rate (1 - specificity)"); ax[0].set_ylabel("Recall")
ax[0].set_title("Validation ROC"); ax[0].legend(loc="lower right")
for i, (name, (ys, ps, ep)) in enumerate(preds.items(), start=1):
    cm = confusion_matrix(ys, (ps >= 0.5).astype(int), labels=[0, 1])
    ax[i].imshow(cm, cmap="Blues")
    for r in range(2):
        for c in range(2):
            ax[i].text(c, r, cm[r, c], ha="center", va="center", fontsize=14)
    ax[i].set_xticks([0, 1], ["Pred normal", "Pred pneumonia"])
    ax[i].set_yticks([0, 1], ["True normal", "True pneumonia"]); ax[i].set_title(f"{name} @ 0.5")
plt.tight_layout(); plt.show()

# %% Cell 8: threshold table per config (shows what weights really change)
torch.save(model.state_dict(), "best_model.pt")
for name, (ys, ps, ep) in preds.items():
    print(f"\n{name}")
    for thr in np.arange(0.1, 0.91, 0.1):
        m = metrics(ys, ps, thr)
        print(f"  thr {thr:.1f}  recall {m['Recall_at_0p5']:.3f}  spec {m['Specificity_at_0p5']:.3f}")
